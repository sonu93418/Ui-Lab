import path from 'path';
import type { UIGenConfig } from '@uigen/config';
import { resolveTheme } from '@uigen/registry';
import { fs } from '@uigen/utils';
import { formatCode } from './formatter.js';

/**
 * Generate the theme CSS file for a project.
 */
export async function generateTheme(
  slug: string,
  options: { cwd: string; config: UIGenConfig }
): Promise<{ success: boolean; file?: string; error?: string }> {
  const { cwd, config } = options;
  const theme = resolveTheme(slug);

  if (!theme) {
    return { success: false, error: `Theme "${slug}" not found.` };
  }

  const { tokens } = theme;

  const cssVars = Object.entries(tokens.colors)
    .map(([k, v]) => `  --color-${k}: ${v};`)
    .join('\n');

  const radiusVars = tokens.radius
    ? Object.entries(tokens.radius)
        .map(([k, v]) => `  --radius-${k}: ${v};`)
        .join('\n')
    : '';

  const shadowVars = tokens.shadows
    ? Object.entries(tokens.shadows)
        .map(([k, v]) => `  --shadow-${k}: ${v};`)
        .join('\n')
    : '';

  const typographyVars = tokens.typography
    ? Object.entries(tokens.typography)
        .map(([k, v]) => `  --${k}: ${v};`)
        .join('\n')
    : '';

  const css = `/* UIGen Theme: ${theme.name} */
/* Generated by UIGen CLI — https://uigen.dev */

@import url('https://fonts.googleapis.com/css2?family=Inter:wght@300;400;500;600;700&family=Outfit:wght@300;400;500;600;700&family=DM+Sans:wght@300;400;500;600;700&display=swap');

:root {
${cssVars}

${radiusVars}

${shadowVars}

${typographyVars}

  --spacing-unit: 0.25rem;
}

${theme.supportsDarkMode ? generateDarkMode(theme) : ''}

* {
  border-color: var(--color-border);
}

body {
  background-color: var(--color-background);
  color: var(--color-foreground);
  font-family: var(--font-sans, system-ui, sans-serif);
}
`;

  const outputPath = path.join(cwd, config.paths.styles, 'theme.css');
  const formatted = await formatCode(css, 'css');
  await fs.writeFile(outputPath, formatted);

  return { success: true, file: outputPath };
}

function generateDarkMode(theme: { tokens: { colors: Record<string, string> } }): string {
  // Produce sensible dark overrides — invert bg/fg and darken surfaces
  const darkOverrides: Record<string, string> = {};
  const c = theme.tokens.colors;

  if (c.background && c.foreground) {
    darkOverrides['background'] = c['foreground'] ?? '#000';
    darkOverrides['foreground'] = c['background'] ?? '#fff';
  }

  if (Object.keys(darkOverrides).length === 0) return '';

  const vars = Object.entries(darkOverrides)
    .map(([k, v]) => `  --color-${k}: ${v};`)
    .join('\n');

  return `
@media (prefers-color-scheme: dark) {
  :root {
${vars}
  }
}

.dark {
${vars}
}
`;
}
